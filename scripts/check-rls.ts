import assert from 'node:assert/strict';
import { createClient } from '@supabase/supabase-js';

const names=['SUPABASE_TEST_URL','SUPABASE_TEST_PUBLISHABLE_KEY','TEST_USER_A_EMAIL','TEST_USER_A_PASSWORD','TEST_USER_B_EMAIL','TEST_USER_B_PASSWORD'];
if(names.some(name=>!process.env[name])) {
  console.error('CHƯA CHẠY: cần cấu hình test Supabase và hai tài khoản thử riêng trong .env.local. Xem README.');
  process.exit(1);
}
const url=process.env.SUPABASE_TEST_URL!;
const key=process.env.SUPABASE_TEST_PUBLISHABLE_KEY!;
const options={auth:{persistSession:false,autoRefreshToken:false}};
const a=createClient(url,key,options);
const b=createClient(url,key,options);
const ids={subject:crypto.randomUUID(),other:crypto.randomUUID(),task:crypto.randomUUID(),session:crypto.randomUUID(),badTask:crypto.randomUUID(),badSession:crypto.randomUUID()};
let ownerA='';
let ownerB='';
let passed=false;
try {
  const loginA=await a.auth.signInWithPassword({email:process.env.TEST_USER_A_EMAIL!,password:process.env.TEST_USER_A_PASSWORD!});
  const loginB=await b.auth.signInWithPassword({email:process.env.TEST_USER_B_EMAIL!,password:process.env.TEST_USER_B_PASSWORD!});
  assert.ok(!loginA.error && loginA.data.user,'Tài khoản thử A chưa đăng nhập được.');
  assert.ok(!loginB.error && loginB.data.user,'Tài khoản thử B chưa đăng nhập được.');
  ownerA=loginA.data.user.id; ownerB=loginB.data.user.id;
  assert.notEqual(ownerA,ownerB,'Phải dùng hai tài khoản khác nhau.');
  assert.equal((await a.from('subjects').insert({id:ids.subject,user_id:ownerA,name:'RLS test A',color:'#123456'})).error,null);
  assert.equal((await b.from('subjects').insert({id:ids.other,user_id:ownerB,name:'RLS test B',color:'#654321'})).error,null);
  const task={id:ids.task,user_id:ownerA,subject_id:ids.subject,title:'RLS test',due_at:'2026-10-22T03:00:00Z',status:'todo'};
  const session={id:ids.session,user_id:ownerA,subject_id:ids.subject,starts_at:'2026-10-22T03:00:00Z',ends_at:'2026-10-22T04:00:00Z'};
  assert.equal((await a.from('tasks').insert(task)).error,null);
  assert.equal((await a.from('class_sessions').insert(session)).error,null);
  for(const [table,id] of [['subjects',ids.subject],['tasks',ids.task],['class_sessions',ids.session]]) {
    const read=await b.from(table).select('id').eq('id',id);
    assert.equal(read.error,null); assert.deepEqual(read.data,[],'B không được đọc dữ liệu A.');
    const update=await b.from(table).update({user_id:ownerB}).eq('id',id).select('id');
    assert.ok(update.error || update.data?.length===0,'B không được sửa dữ liệu A.');
    const remove=await b.from(table).delete().eq('id',id).select('id');
    assert.ok(remove.error || remove.data?.length===0,'B không được xóa dữ liệu A.');
    const stillThere=await a.from(table).select('id,user_id').eq('id',id).single();
    assert.equal(stillThere.error,null); assert.equal(stillThere.data?.user_id,ownerA);
  }
  assert.ok((await b.from('tasks').insert({...task,id:ids.badTask,user_id:ownerB})).error,'FK phải chặn task B vào môn A.');
  assert.ok((await b.from('class_sessions').insert({...session,id:ids.badSession,user_id:ownerB})).error,'FK phải chặn buổi học B vào môn A.');
  assert.ok((await b.from('tasks').insert({...task,id:ids.badTask})).error,'Không được giả user_id của A.');
  assert.ok((await a.from('tasks').update({subject_id:ids.other}).eq('id',ids.task)).error,'Không được chuyển task sang môn B.');
  assert.ok((await a.from('subjects').update({user_id:ownerB}).eq('id',ids.subject)).error,'Không được đổi chủ sở hữu.');
  assert.ok((await a.from('subjects').delete().eq('id',ids.subject)).error,'Không xóa môn đang có dữ liệu.');
  const anonymous=createClient(url,key,options);
  const anonymousRead=await anonymous.from('tasks').select('id').eq('id',ids.task);
  assert.ok(anonymousRead.error || anonymousRead.data?.length===0,'Chưa đăng nhập không được đọc task.');
  assert.equal((await a.from('tasks').update({status:'done'}).eq('id',ids.task)).error,null);
  assert.equal((await a.from('tasks').select('status').eq('id',ids.task).single()).data?.status,'done');
  passed=true;
} finally {
  // Only remove UUIDs generated by this run, including rows left by failed security assertions.
  for(const client of [a,b]) {
    for(const [table,recordIds] of [
      ['tasks',[ids.task,ids.badTask]],['class_sessions',[ids.session,ids.badSession]],['subjects',[ids.subject,ids.other]],
    ] as const) {
      const {error}=await client.from(table).delete().in('id',[...recordIds]);
      if(error) { passed=false; console.error(`Cleanup ${table} chưa thành công; kiểm tra các bản ghi thử của lần chạy này.`); }
    }
    await client.auth.signOut();
  }
}
if(!passed) process.exitCode=1;
else console.log('PASS: CRUD chủ sở hữu, RLS A/B, FK ghép, chặn giả owner, anonymous và xóa môn có dữ liệu.');
